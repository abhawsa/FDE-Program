"""Renders the Markdown run report: risk ranking, review outcomes, coverage delta."""
from __future__ import annotations

from typing import Any, Dict, List


def render_risk_table(candidates: List[Dict[str, Any]], limit: int = 25) -> str:
    if not candidates:
        return "_No untested, risk-ranked paths were found._"
    lines = [
        "| Rank | File | Function | Risk Score | Change Freq | Complexity | Coverage Gap |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, c in enumerate(candidates[:limit], start=1):
        lines.append(
            f"| {i} | `{c['file']}` | `{c['qualname']}` | {c['risk_score']:.3f} | "
            f"{c['change_frequency']} | {c['complexity']} | {c['coverage_gap'] * 100:.0f}% |"
        )
    return "\n".join(lines)


def render_draft_outcomes(drafts: List[Dict[str, Any]]) -> str:
    if not drafts:
        return "_No candidate tests were drafted._"
    lines = [
        "| Draft ID | File | Function | Risk | Generated By | Status | Low-Value Flag | Reviewer |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in drafts:
        c = d["candidate"]
        low_value = "warning: yes" if d["low_value"] else "no"
        lines.append(
            f"| `{d['id']}` | `{c['file']}` | `{c['qualname']}` | {c['risk_score']:.3f} | "
            f"{d['generated_by']} | {d['status']} | {low_value} | {d.get('reviewer') or '-'} |"
        )
    return "\n".join(lines)


def render_coverage_delta(delta: Dict[str, Any]) -> str:
    lines = [
        f"- Overall coverage: **{delta['overall_before']:.1f}% -> {delta['overall_after']:.1f}%** "
        f"({delta['overall_delta']:+.1f} pts), computed from APPROVED/EDITED drafts only.",
        "",
    ]
    if delta.get("per_file"):
        lines.append("| File | Before | After | Delta |")
        lines.append("|---|---|---|---|")
        for file_name, v in delta["per_file"].items():
            lines.append(f"| `{file_name}` | {v['before']:.1f}% | {v['after']:.1f}% | {v['delta']:+.1f} |")
    else:
        lines.append("_No per-file coverage changes detected._")
    return "\n".join(lines)


def build_markdown_report(state: Dict[str, Any]) -> str:
    sections = ["# AI Test Coverage & Regression Risk Agent - Run Report", ""]

    sections.append("## 1. Risk-Ranked Untested Paths")
    sections.append(
        "Ranked by `risk_score = w1*change_frequency + w2*complexity + w3*coverage_gap` "
        "(not by coverage gap alone)."
    )
    sections.append(render_risk_table(state.get("candidates", [])))
    sections.append("")

    sections.append("## 2. Candidate Test Review Outcomes")
    sections.append(render_draft_outcomes(state.get("drafts", [])))
    sections.append("")

    apply_result = state.get("apply_result")
    if apply_result:
        sections.append("## 3. Apply Summary")
        sections.append(f"- Applied to test suite: {len(apply_result.get('applied', []))}")
        sections.append(f"- Conflicts (flagged, not overwritten): {len(apply_result.get('conflicts', []))}")
        sections.append(f"- Skipped (not approved/edited): {len(apply_result.get('skipped', []))}")
        if apply_result.get("conflicts"):
            for conflict in apply_result["conflicts"]:
                sections.append(f"  - CONFLICT: `{conflict['draft_id']}` -> `{conflict['path']}` needs manual resolution")
        sections.append("")

    if state.get("coverage_delta"):
        sections.append("## 4. Coverage Delta (approved tests only)")
        sections.append(render_coverage_delta(state["coverage_delta"]))
        sections.append("")

    sections.append("## 5. Audit Trail")
    sections.append(
        f"Full append-only log at `{state.get('audit_log_path', 'data/audit_log.jsonl')}` - "
        "every draft links back to its risk score/components, and every review decision "
        "records its reviewer."
    )
    return "\n".join(sections)
